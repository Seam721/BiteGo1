-- Ensure order item subtotals exist for existing installations.
alter table public.order_items
  add column if not exists subtotal numeric(12,2) not null default 0;

-- Backfill legacy rows where subtotal was not previously stored.
update public.order_items
set subtotal = coalesce(subtotal, price * quantity, 0)
where subtotal is null or subtotal = 0;

-- Older versions of the app used item_name. Keep it if it exists, but make the new
-- admin app use the standard "name" column.
alter table public.order_items add column if not exists name text;
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema='public' AND table_name='order_items' AND column_name='item_name') THEN
    UPDATE public.order_items SET name = COALESCE(name, item_name) WHERE name IS NULL;
  END IF;
END $$;

