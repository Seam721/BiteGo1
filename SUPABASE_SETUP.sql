-- PUBLIC CUSTOMER POLICIES
-- =========================
-- The customer storefront accesses private order/payment data through the
-- backend API. Keep public catalog reads available, but never expose every
-- customer's orders or payments through the publishable browser key.
DO $$
BEGIN
  EXECUTE 'drop policy if exists foodie6_public_restaurants_select on public.restaurants';
  EXECUTE 'drop policy if exists foodie6_public_categories_select on public.categories';
  EXECUTE 'drop policy if exists foodie6_public_menu_items_select on public.menu_items';
  EXECUTE 'drop policy if exists foodie6_public_orders_insert on public.orders';
  EXECUTE 'drop policy if exists foodie6_public_orders_select on public.orders';
  EXECUTE 'drop policy if exists foodie6_public_order_items_insert on public.order_items';
  EXECUTE 'drop policy if exists foodie6_public_payments_insert on public.payments';
  EXECUTE 'drop policy if exists foodie6_public_payments_select on public.payments';
  EXECUTE 'drop policy if exists foodie6_public_customers_insert on public.customers';
  CREATE POLICY foodie6_public_restaurants_select ON public.restaurants
    FOR SELECT TO anon, authenticated USING (status = 'active');
  CREATE POLICY foodie6_public_categories_select ON public.categories
    FOR SELECT TO anon, authenticated USING (status = 'active');
  CREATE POLICY foodie6_public_menu_items_select ON public.menu_items
    FOR SELECT TO anon, authenticated USING (available = true);
END $$;

-- BiteGo payment security note:
-- Do NOT add an anon/authenticated INSERT policy on public.payments.
-- The customer browser calls the BiteGo backend; the backend writes payment
-- attempts using SUPABASE_SERVICE_ROLE_KEY or SUPABASE_SECRET_KEY stored only
-- in backend/.env. This preserves RLS and prevents customers forging payment rows.
--
-- Backend configuration requirement:
-- Set SUPABASE_SERVICE_ROLE_KEY (or SUPABASE_SECRET_KEY) only in backend/.env (never in frontend/admin).
-- The server uses this key for order/payment operations and validates admin JWTs
-- before allowing any backend management endpoint.
